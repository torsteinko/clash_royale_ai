"""
YOLO Training Script for Synthetic Clash Royale Dataset

This script trains a YOLO model on the synthetic dataset generated by
build_synthetic_dataset.py. It's designed to work with the comprehensive
sprite-based dataset that includes ally/enemy variants for all troops.

Usage:
    python train_yolo_synthetic.py [options]

Options:
    --data: Path to data.yaml file (default: auto-detect)
    --model: Base YOLO model to use (default: yolo11l.pt)
    --epochs: Number of training epochs (default: 150)
    --imgsz: Training image size (default: 640)
    --batch: Batch size (default: auto)
    --device: Training device (default: auto)
    --resume: Resume from checkpoint (default: False)
"""

import argparse
import os
import sys
from pathlib import Path
from datetime import datetime
